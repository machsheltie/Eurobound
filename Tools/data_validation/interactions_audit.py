"""Audit a city's *_interactions.json: list every entity it names and where canon defines it.

Bead Eurobound-fx3d (2026-11-18). Reusable for every city:

    python -I Tools/data_validation/interactions_audit.py \
        game/assets/data/locations/debaucheryville/debaucheryville_interactions.json \
        --mirror Assets/Data/locations/debaucheryville/debaucheryville_interactions.json \
        --out %TEMP%/fx3d_audit.json

What it does:
  1. Walks the live file and pulls out every referenced id, sorted into types
     (location, npc, villain, boss, item, nft, quest, status, flag, achievement/title,
     machine, graffiti, encounter, unlock) by the key that holds it (KEY_TYPES below).
  2. Looks each id up in: docs/catalog/catalog.json (generated by Tools/catalog/build_catalog.py),
     the engine registries under game/assets/data/ (items, statuses, quest flags, enemies,
     NPC profiles, quests), and a plain-text grep of design/ and the rulings ledger for the id
     and for its humanised words. It prints candidate doc:line hits; a person still reads
     those lines to decide ok / mismatch / no doc. The script never decides canon.
  3. With --mirror, compares every quoted string in the mirror copy against the live file and
     lists the strings found only in the mirror, grouped under the mirror location section they
     sit in. The mirror does not need to be valid JSON (the Debaucheryville one is not).

Stdlib only. Read-only: it writes nothing but the --out file.
"""
from __future__ import annotations

import argparse
import json
import re
import subprocess
import sys
from collections import defaultdict
from pathlib import Path

REPO = Path(__file__).resolve().parents[2]

# key in the interactions JSON -> entity type. Values may be a string, a list of strings,
# or (set_flags / flag dicts) a dict whose keys are the ids.
KEY_TYPES = {
    "npc_id": "npc", "npc": "npc", "host_npc": "npc", "host_id": "npc",
    "villain_ids": "villain", "boss_id": "boss",
    "item_id": "item", "item": "item", "item_gained": "item", "items_gained": "item",
    "trigger_items": "item", "gag_item": "item", "hidden_item": "item", "inventory": "item",
    "premium_items": "item", "item_requirements": "item",
    "nft_item_id": "nft", "nft_name": "nft", "target_nft": "nft", "nft_vault_key": "nft",
    "nft_file": "nft",
    "quest_id": "quest",
    "status": "status", "status_applied": "status", "status_effect": "status",
    "status_application": "status",
    "set_flags": "flag", "flag": "flag", "completion_flag": "flag", "success_flag": "flag",
    "failure_flag": "flag", "icq_contact": "flag",
    "achievement": "achievement", "achievement_unlock": "achievement",
    "completion_reward": "achievement", "title_unlock": "achievement",
    "machine_id": "machine", "graffiti_id": "graffiti", "encounter_id": "encounter",
    "unlock_id": "unlock", "area_id": "location", "previous_brewery": "location",
    "next_brewery": "location", "destination": "location", "final_destination": "location",
    "next_location": "location", "location_id": "location",
}
# keys whose dict-children are status ids (status_effect_management.<x>_status)
STATUS_BLOCKS = {"status_effect_management"}
STATUS_BLOCK_MARKERS = {"cure_methods", "duration", "gameplay_effect", "sources", "source"}
SKIP_VALUES = {"none", "true", "false", ""}
# Not canon: hits here are reported separately as "legacy only".
NON_CANON = ("design/legacy/", "design/templates/")

ID_RX = re.compile(r"^[a-z0-9_#.\-]+$")
QUOTED = re.compile(r'"((?:[^"\\]|\\.)*)"')


def walk(node, path, out):
    if isinstance(node, dict):
        for k, v in node.items():
            p = f"{path}.{k}" if path else k
            t = KEY_TYPES.get(k)
            if t:
                vals = []
                if isinstance(v, str):
                    vals = [v]
                elif isinstance(v, list):
                    vals = [x for x in v if isinstance(x, str)]
                elif isinstance(v, dict) and k == "set_flags":
                    vals = list(v)
                for x in vals:
                    if x.lower() not in SKIP_VALUES:
                        out[(t, x)].append(p)
            if k in STATUS_BLOCKS and isinstance(v, dict):
                for sk, sv in v.items():   # only real status blocks, not e.g. environmental_effects
                    if isinstance(sv, dict) and (STATUS_BLOCK_MARKERS & set(sv)):
                        out[("status", sk)].append(f"{p}.{sk}")
            walk(v, p, out)
    elif isinstance(node, list):
        for i, v in enumerate(node):
            walk(v, f"{path}[{i}]", out)


def humanise(eid):
    s = eid
    for pre in ("debaucheryville_villain_", "debaucheryville_npc_", "debaucheryville_", "item_nft_",
                "item_", "npc_"):
        if s.startswith(pre):
            s = s[len(pre):]
            break
    s = re.sub(r"_0\d$", "", s)
    s = re.sub(r"_status$", "", s)
    return s.replace("_", " ").strip()


def load(rel):
    p = REPO / rel
    try:
        return json.loads(p.read_text(encoding="utf-8"))
    except Exception:
        return None


def registries():
    reg = {}
    d = "game/assets/data/"
    for rel, key in (("items/consumables.json", "consumables"), ("items/key_items.json", "key_items"),
                     ("items/equipment.json", "equipment"), ("skills/status_effects.json", "status_effects"),
                     ("world_data/quest_flags.json", "flags"),
                     ("enemies/debaucheryville_enemies.json", "enemies"),
                     ("nft/legacy_vault.json", None)):
        doc = load(d + rel) or {}
        coll = doc.get(key) if key else doc
        if isinstance(coll, dict):
            reg[rel] = set(coll)
        elif isinstance(coll, list):
            reg[rel] = {x.get("id") for x in coll if isinstance(x, dict)}
    for p in sorted((REPO / d / "npcs/base_profiles").glob("*.json")):
        doc = load(p.relative_to(REPO).as_posix()) or {}
        npcs = doc.get("npcs", doc)
        rel = p.relative_to(REPO / d).as_posix()
        reg[rel] = set(npcs) if isinstance(npcs, dict) else {x.get("npc_id") or x.get("id")
                                                              for x in npcs if isinstance(x, dict)}
    return reg


def catalog_index():
    cat = load("docs/catalog/catalog.json") or {}
    idx = {}
    for c in cat.get("categories", []):
        for r in c.get("rows", []):
            for key in (r.get("id"), (r.get("name") or "").lower()):
                if key:
                    idx.setdefault(key, []).append((c["id"], r.get("name"), r.get("doc"), r.get("status")))
    return idx


def corpus():
    files = []
    for p in sorted((REPO / "design").rglob("*")):
        if p.suffix.lower() in (".md", ".json") and p.is_file():
            files.append(p)
    files.append(REPO / "docs/superpowers/NEXT_WORK.md")
    lines = []
    for p in files:
        try:
            text = p.read_text(encoding="utf-8", errors="replace")
        except OSError:
            continue
        rel = p.relative_to(REPO).as_posix()
        for n, line in enumerate(text.splitlines(), 1):
            lines.append((rel, n, line.lower()))
    return lines


def grep(lines, needle, limit=4, legacy=False):
    n = needle.lower()
    hits = []
    for rel, ln, text in lines:
        if rel.startswith(NON_CANON) != legacy:
            continue
        if n in text:
            hits.append(f"{rel}:{ln}")
            if len(hits) >= limit:
                break
    return hits


def canon_search(query, k=3):
    """Keyword-mode canon index search (stdlib only, fast). Returns path:line hits."""
    script = REPO / "tools/canon_index/canon_index.py"
    if not script.exists():
        return []
    try:
        r = subprocess.run([sys.executable, "-I", str(script), "search", query, "--mode", "keyword",
                            "--json", "-k", str(k)], capture_output=True, text=True, encoding="utf-8",
                           timeout=60, cwd=REPO)
        return [f"{h['path']}:{h['line']}" for h in json.loads(r.stdout or "[]")]
    except Exception:
        return []


def mirror_diff(live_text, mirror_path, live_path):
    """Strings in the mirror that the live file lacks, grouped by mirror section.

    Each string is tagged with the sibling live file(s) (same folder as the live file) that
    still hold it, so content that only moved between files is told apart from content that
    exists nowhere in the live tree."""
    live_strings = set(QUOTED.findall(live_text))
    siblings = {}
    for sib in sorted(Path(live_path).parent.glob("*.json")):
        if sib.resolve() != Path(live_path).resolve():
            siblings[sib.name] = set(QUOTED.findall(sib.read_text(encoding="utf-8", errors="replace")))
    text = Path(mirror_path).read_text(encoding="utf-8", errors="replace")
    section, sec_id = "(top)", None
    out = defaultdict(list)
    for n, line in enumerate(text.splitlines(), 1):
        m = re.search(r'"(debaucheryville_[a-z0-9_]+_\d\d)"', line)
        if m and ('"location_id"' in line or re.match(r'\s{4}"debaucheryville_', line)) \
                and m.group(1) != sec_id:
            sec_id = m.group(1)
            section = f"{sec_id} (mirror line {n})"
        for s in QUOTED.findall(line):
            if s not in live_strings:
                out[section].append((n, s, [k for k, v in siblings.items() if s in v]))
    return out


def main(argv=None):
    ap = argparse.ArgumentParser(description=__doc__.splitlines()[0])
    ap.add_argument("live")
    ap.add_argument("--mirror")
    ap.add_argument("--out", help="write the full result as JSON here")
    ap.add_argument("--no-grep", action="store_true", help="skip the design/ grep (fast)")
    ap.add_argument("--canon", action="store_true",
                    help="also run a keyword canon-index search for each entity's humanised name")
    a = ap.parse_args(argv)

    live_text = Path(a.live).read_text(encoding="utf-8")
    data = json.loads(live_text)
    found = defaultdict(list)
    walk(data, "", found)
    for lid in (data.get("locations") or {}):
        found[("location", lid)].append(f"locations.{lid}")

    reg = registries()
    cat = catalog_index()
    lines = [] if a.no_grep else corpus()
    rows = []
    for (etype, eid), paths in sorted(found.items()):
        human = humanise(eid)
        engine = [rel for rel, ids in reg.items() if eid in ids]
        catalog = cat.get(eid, []) + [c for c in cat.get(human, []) if c not in cat.get(eid, [])]
        g_id = grep(lines, eid) if lines and ID_RX.match(eid) else []
        g_name = grep(lines, human) if lines and len(human) > 4 and human != eid else []
        legacy = (grep(lines, eid, 2, legacy=True) or grep(lines, human, 2, legacy=True)) if lines else []
        canon = canon_search(human) if a.canon else []
        rows.append({"type": etype, "id": eid, "human": human, "paths": sorted(set(paths)),
                     "engine": engine, "catalog": catalog, "grep_id": g_id, "grep_name": g_name,
                     "legacy": legacy, "canon_index": canon})

    result = {"live": a.live, "entities": rows}
    if a.mirror:
        result["mirror_only"] = {k: v for k, v in mirror_diff(live_text, a.mirror, a.live).items()}
    if a.out:
        Path(a.out).write_text(json.dumps(result, ensure_ascii=False, indent=1), encoding="utf-8")
    by_type = defaultdict(int)
    for r in rows:
        by_type[r["type"]] += 1
    print(f"{len(rows)} entities: " + ", ".join(f"{t} {n}" for t, n in sorted(by_type.items())))
    nodoc = [r for r in rows if not (r["catalog"] or r["grep_id"] or r["grep_name"] or r["engine"])]
    print(f"{len(nodoc)} with no hit in catalog, engine or canon design grep "
          f"({sum(1 for r in nodoc if r['legacy'])} of them only in design/legacy)")
    if a.mirror:
        allm = [x for v in result["mirror_only"].values() for x in v]
        print(f"mirror-only strings: {len(allm)} in {len(result['mirror_only'])} sections; "
              f"{sum(1 for x in allm if not x[2])} of them in no sibling live file either")
    return 0


if __name__ == "__main__":
    sys.exit(main())
